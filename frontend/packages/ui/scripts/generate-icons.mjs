import { readFile, readdir, rm, mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { transform } from '@svgr/core'
import jsxPlugin from '@svgr/plugin-jsx'
import svgoPlugin from '@svgr/plugin-svgo'

const packageRoot = fileURLToPath(new URL('..', import.meta.url))
const sourceRoot = path.join(packageRoot, 'src/assets/icons')
const outputRoot = path.join(packageRoot, 'src/icons')
const generatedFileHeader = '// Generated by packages/ui/scripts/generate-icons.mjs. Do not edit.\n'

function toPascalCase(value) {
  return value
    .split('-')
    .map(part => `${part.charAt(0).toUpperCase()}${part.slice(1)}`)
    .join('')
}

function iconTemplate(variables, { tpl }) {
  return tpl`
import type { SVGProps } from 'react'

export function ${variables.componentName}(props: SVGProps<SVGSVGElement>) {
  return ${variables.jsx}
}
`
}

async function collectSources() {
  const sizeDirectories = (await readdir(sourceRoot, { withFileTypes: true }))
    .filter(entry => entry.isDirectory() && /^\d+$/.test(entry.name))
    .toSorted((left, right) => Number(left.name) - Number(right.name))
  const sources = []
  const componentNames = new Set()

  for (const sizeDirectory of sizeDirectories) {
    const size = Number(sizeDirectory.name)
    const directory = path.join(sourceRoot, sizeDirectory.name)
    const files = (await readdir(directory))
      .filter(file => file.endsWith('.svg'))
      .toSorted((left, right) => left.localeCompare(right))

    for (const file of files) {
      const baseName = path.basename(file, '.svg')

      if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(baseName)) {
        throw new Error(`Icon source must use kebab-case: ${sizeDirectory.name}/${file}`)
      }

      const componentName = `${toPascalCase(baseName)}Icon`

      if (componentNames.has(componentName)) {
        throw new Error(`Duplicate generated icon component: ${componentName}`)
      }

      componentNames.add(componentName)
      sources.push({ baseName, componentName, file: path.join(directory, file), size })
    }
  }

  return sources
}

async function generateIcon({ baseName, componentName, file, size }) {
  const source = await readFile(file, 'utf8')
  const svgTag = source.match(/<svg\b[^>]*>/)?.[0]
  const width = svgTag?.match(/\bwidth="(\d+)"/)?.[1]
  const height = svgTag?.match(/\bheight="(\d+)"/)?.[1]

  if (width !== String(size) || height !== String(size)) {
    throw new Error(`Icon dimensions must match its ${size}px source directory: ${file}`)
  }

  const component = await transform(
    source,
    {
      expandProps: 'end',
      jsxRuntime: 'automatic',
      plugins: [svgoPlugin, jsxPlugin],
      svgProps: {
        'aria-hidden': true,
        focusable: 'false',
      },
      svgoConfig: {
        plugins: [
          {
            name: 'preset-default',
            params: {
              overrides: {
                convertColors: {
                  currentColor: true,
                },
                removeViewBox: false,
              },
            },
          },
          {
            name: 'prefixIds',
            params: {
              delim: '_',
              prefix: baseName,
              prefixIds: true,
              prefixClassNames: false,
            },
          },
          {
            name: 'removeAttrs',
            params: {
              attrs: 'style',
            },
          },
        ],
      },
      template: iconTemplate,
      typescript: true,
    },
    { componentName }
  )

  if (/(?:#[0-9a-f]{3,8}|["'](?:black|white)["'])/i.test(component)) {
    throw new Error(`Generated UI icon contains a fixed color instead of currentColor: ${file}`)
  }

  await writeFile(
    path.join(outputRoot, `${baseName}-icon.tsx`),
    `${generatedFileHeader}${component}`
  )
}

const sources = await collectSources()

await rm(outputRoot, { force: true, recursive: true })
await mkdir(outputRoot, { recursive: true })
await Promise.all(sources.map(generateIcon))

console.log(`Generated ${sources.length} icon components.`)
